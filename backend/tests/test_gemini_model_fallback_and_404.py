# ── 1. Model Fallback on HTTP 404 ───────────────────────────────────────────

@pytest.mark.asyncio
async def test_unsupported_model_returns_404_falls_back_to_valid_candidate(monkeypatch):
    """When configured model returns 404, it immediately falls back to the next supported candidate."""
    _setup_test_env(monkeypatch)
    monkeypatch.setenv("GEMINI_MODEL", "gemini-nonexistent-model")
    _cfg.get_settings.cache_clear()

    call_history = []

    async def mock_execute(client, model, base_url, api_key, payload, timeout=None):
        call_history.append(model)
        if model == "gemini-nonexistent-model":
            return 404, {"error": {"code": 404, "message": "Model not found."}}, "Model not found"
        # First fallback candidate succeeds
        return 200, {
            "candidates": [{
                "content": {
                    "parts": [{"text": f"Response generated by fallback model {model}."}],
                    "role": "model",
                },
                "finishReason": "STOP",
            }]
        }, "{}"

    with patch("app.services.gemini.client._execute_gemini_request", side_effect=mock_execute):
        text = await generate_gemini_response("Summarize recent AMOC findings.")

    assert "Response generated by fallback model" in text
    assert call_history[0] == "gemini-nonexistent-model"
    # Verify fallback model was called without repeating the failed model
    assert len(call_history) == 2
    assert call_history[1] == FALLBACK_MODELS[0] or call_history[1] in FALLBACK_MODELS
    assert get_last_active_gemini_model() == call_history[1]


# ── 2. All Gemini Candidates Unavailable ─────────────────────────────────────

@pytest.mark.asyncio
async def test_all_gemini_candidates_404_raises_clean_error(monkeypatch):
    """When all Gemini candidates return 404, raises clean gemini_model_not_found error."""
    _setup_test_env(monkeypatch)

    async def mock_execute(client, model, base_url, api_key, payload, timeout=None):
        return 404, {"error": {"code": 404, "message": f"Model {model} is discontinued."}}, "404"

    with patch("app.services.gemini.client._execute_gemini_request", side_effect=mock_execute):
        with pytest.raises(GeminiServiceError) as exc_info:
            await generate_gemini_response("What is AMOC?")

    assert exc_info.value.status_code == 502
    assert exc_info.value.error_code == "gemini_model_not_found"
    assert "discontinued" in exc_info.value.message or "not found" in exc_info.value.message


# ── 3. Groq Fallback on Gemini 404 for Text Research ─────────────────────────

@pytest.mark.asyncio
async def test_gemini_404_triggers_groq_fallback_for_text_research(monkeypatch):
    """When Gemini models return 404 on text research, router transparently falls back to Groq."""
    _setup_test_env(monkeypatch)

    gemini_404 = GeminiServiceError(
        "Gemini model 'gemini-3.8-flash' was not found or is discontinued.",
        status_code=502,
        error_code="gemini_model_not_found",
    )

    with patch("app.services.ai.router.generate_gemini_response", new=AsyncMock(side_effect=gemini_404)), \
         patch("app.services.ai.router.generate_groq_response", new=AsyncMock(return_value=(
             "Groq research synthesis on AMOC stability and tipping indicators.",
             "Groq (llama-3.3-70b-versatile)"
         ))):
        result = await route_and_generate("What are the latest findings about AMOC stability?")

    assert result.provider == "Groq"
    assert result.fallback_occurred is True
    assert "Groq research synthesis" in result.content


# ── 4. Multimodal Vision Never Falls Back to Groq ────────────────────────────

@pytest.mark.asyncio
async def test_multimodal_vision_never_routes_to_groq_on_gemini_404(monkeypatch):
    """Multimodal vision requests require Gemini and MUST NEVER route to text-only Groq on failure."""
    _setup_test_env(monkeypatch)

    gemini_404 = GeminiServiceError(
        "Gemini model was not found.",
        status_code=502,
        error_code="gemini_model_not_found",
    )

    mock_images = [{"mime_type": "image/png", "data": "base64data"}]

    with patch("app.services.ai.router.generate_gemini_response", new=AsyncMock(side_effect=gemini_404)), \
         patch("app.services.ai.router.generate_groq_response", new=AsyncMock()) as mock_groq:
        with pytest.raises(GeminiServiceError) as exc_info:
            await route_and_generate(
                prompt="Describe this flood damage photo.",
                images=mock_images,
            )
        assert exc_info.value.status_code == 502
        assert exc_info.value.error_code == "gemini_model_not_found"
        mock_groq.assert_not_awaited()


# ── 5. Invalid API Key Raises Immediately (No Retry Loop) ────────────────────

@pytest.mark.asyncio
async def test_invalid_api_key_raises_immediately_without_retry(monkeypatch):
    """Gemini 401/403 authorization errors must raise immediately without looping through candidates."""
    _setup_test_env(monkeypatch)

    attempts = []

    async def mock_execute(client, model, base_url, api_key, payload, timeout=None):
        attempts.append(model)
        return 401, {"error": {"code": 401, "message": "API_KEY_INVALID"}}, "401"

    with patch("app.services.gemini.client._execute_gemini_request", side_effect=mock_execute):
        with pytest.raises(GeminiServiceError) as exc_info:
            await generate_gemini_response("Explain greenhouse effect")

    assert exc_info.value.status_code == 502
    assert exc_info.value.error_code == "gemini_auth_error"
    # Must only have tried once (no useless sequential retries with an invalid key)
    assert len(attempts) == 1


